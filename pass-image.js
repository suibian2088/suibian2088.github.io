  if(theme.solid)ctx.fill(new Path2D(theme.path));else ctx.stroke(new Path2D(theme.path));ctx.restore();
  ctx.font=`28px ${sans}`;ctx.fillStyle='#203b35';ctx.fillText('新成员通行证',132,858);
