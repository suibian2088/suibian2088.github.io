  while(ctx.measureText(name).width>1030&&size>48){size-=4;ctx.font=`600 ${size}px ${sans}`;}
  ctx.fillStyle='#203b35';ctx.fillText(name,128,512);
  ctx.font=`32px ${sans}`;const deptWidth=ctx.measureText(department).width;
  ctx.fillStyle=theme.accent;ctx.beginPath();ctx.roundRect(132,578,deptWidth+48,64,10);ctx.fill();
